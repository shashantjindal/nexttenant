package com.nexttenant.photo;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Optional;
import java.util.regex.Pattern;

/**
 * Stores photos on the local filesystem, for development.
 *
 * <p>{@code @ConditionalOnProperty} with {@code matchIfMissing} rather than
 * {@code @ConditionalOnMissingBean}: the property is evaluated
 * deterministically, whereas "is another bean of this type defined?" depends on
 * registration order and produces intermittent wiring failures. This is the
 * same lesson ConsoleSmsSender taught in phase 5.
 */
@Component
@ConditionalOnProperty(name = "nexttenant.photos.storage",
                       havingValue = "local", matchIfMissing = true)
public class LocalPhotoStorage implements PhotoStorage {

    private static final Logger log = LoggerFactory.getLogger(LocalPhotoStorage.class);

    /**
     * Keys are generated by us and look like
     * {@code listings/<uuid>/<uuid>.jpg}. The pattern is enforced anyway.
     *
     * <p>A key reaching the filesystem is a path, and a path containing
     * {@code ../} escapes the directory — the classic traversal. Validating
     * against a strict allowlist is cheaper than reasoning about whether every
     * caller sanitised its input.
     */
    private static final Pattern SAFE_KEY =
            Pattern.compile("^[a-zA-Z0-9/_-]+[.](jpg|jpeg|png|webp)$");

    private final Path root;

    public LocalPhotoStorage(@Value("${nexttenant.photos.local-dir:./data/photos}") String directory) {
        this.root = Path.of(directory).toAbsolutePath().normalize();
        try {
            Files.createDirectories(root);
            log.info("Photos stored locally under {}", root);
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot create photo directory " + root, e);
        }
    }

    @Override
    public void put(String key, byte[] bytes) {
        Path target = resolve(key);
        try {
            Files.createDirectories(target.getParent());
            Files.write(target, bytes);
        } catch (IOException e) {
            throw new UncheckedIOException("Could not store photo " + key, e);
        }
    }

    @Override
    public Optional<byte[]> get(String key) {
        Path target = resolve(key);
        if (!Files.isRegularFile(target)) {
            return Optional.empty();
        }
        try {
            return Optional.of(Files.readAllBytes(target));
        } catch (IOException e) {
            throw new UncheckedIOException("Could not read photo " + key, e);
        }
    }

    @Override
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException e) {
            log.warn("Could not delete photo {}", key);
        }
    }

    @Override
    public boolean exists(String key) {
        return Files.isRegularFile(resolve(key));
    }

    /**
     * Resolves a key to a path, refusing anything that escapes the root.
     *
     * <p>Two layers: the pattern rejects "..", and the normalised path is
     * checked to still start with the root. The second catches anything the
     * first missed — encoding tricks, symlinks, platform quirks — because a
     * single regex is a thin thing to rest a filesystem on.
     */
    private Path resolve(String key) {
        if (key == null || !SAFE_KEY.matcher(key).matches()) {
            throw new IllegalArgumentException("Invalid photo key");
        }
        Path resolved = root.resolve(key).normalize();
        if (!resolved.startsWith(root)) {
            throw new IllegalArgumentException("Invalid photo key");
        }
        return resolved;
    }
}
